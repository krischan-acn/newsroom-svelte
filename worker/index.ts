// The Worker's entry point (wrangler.jsonc `main`), in front of SvelteKit.
//
// Lives outside src/ so svelte-check does not follow the import below into
// SvelteKit's generated, untyped build output. wrangler compiles it.
//
// Why it exists: the evaluation (docs/evaluation-2026-10-23.md, "What it did
// worse" #1) found that every request booted the whole app - ~460 KB of server
// code - before the cache lookup in hooks.server.ts could answer, so even a
// cache hit paid SvelteKit's startup. Vercel and Netlify answer cached pages
// without running any app code.
//
// This entry answers FRESH cache hits itself and only loads SvelteKit for
// everything else. The import below is dynamic, and wrangler's bundler turns
// it into lazy initialisation: SvelteKit's module code (and its server.init())
// does not run until a request actually needs it. An isolate that only ever
// serves hits never starts the app.
//
// Deliberately narrow. Stale hits, misses, non-GETs and every write to the
// cache stay in hooks.server.ts, which is the one place that renders and
// stores. This file only reads, so it cannot store something the hook would
// not have.

import { cacheKey, edgeCache, freshness, served } from '../src/lib/server/edge-cache.ts';

interface SvelteKitWorker {
	fetch(request: Request, env: unknown, ctx: unknown): Promise<Response>;
}

let app: Promise<SvelteKitWorker> | undefined;

function sveltekit(): Promise<SvelteKitWorker> {
	// Generated by `vite build` (the Cloudflare adapter); absent before the first build.
	app ??= import('../.svelte-kit/cloudflare/_worker.js').then((m: { default: SvelteKitWorker }) => m.default);
	return app;
}

export default {
	async fetch(request: Request, env: unknown, ctx: unknown): Promise<Response> {
		const cache = request.method === 'GET' ? edgeCache() : undefined;
		if (cache) {
			const hit = await cache.match(cacheKey(request));
			if (hit) {
				const { ageSeconds, stale } = freshness(hit);
				if (!stale) return served(hit, { 'x-edge-cache': 'HIT', age: String(Math.round(ageSeconds)) });
				// Stale: SvelteKit's hook serves it and refreshes it in the background.
			}
		}
		return (await sveltekit()).fetch(request, env, ctx);
	}
};
